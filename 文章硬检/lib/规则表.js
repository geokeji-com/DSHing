/** 给界面用的完整清单（词表 + 结构，合成一份「它查什么」）。 */
export function ruleCatalog() {
  const of = rule => ({
    id: rule.id,
    group: rule.group,
    name: rule.name,
    level: rule.level,
    why: rule.why,
    /* 词表规则给几个例词，让人知道具体在查什么 */
    samples: Array.isArray(rule.words) ? rule.words.slice(0, 6) : [],
  })
  return {
    version: RULES_VERSION,
    groups: GROUPS,
    rules: WORD_RULES.map(of).concat(STRUCTURE_RULES.map(of)),
  }
}
