/* 硬检规则表 —— 通用文字硬检的**唯一真相**。
 *
 * 这份表跟客户、跟知识库**无关**。它只查「一眼就知道不能发」的东西：
 * 我们交代给 agent 的话漏进了正文、广告法不让写的词、Markdown 结构坏了。
 *
 * 分两套机制（分三组只是给人看的分类）：
 *   1. 词表匹配 —— 本文件的 WORD_RULES。出现就标。
 *   2. 结构检查 —— 数数量和形状（`**` 几个、表格几列、标题几级），
 *      规则清单在本文件 STRUCTURE_RULES，实现在 执行器.js。
 *
 * 它**做不到**的事（写清楚，避免有人对它有错误期待）：
 *   - 看不懂文章写得好不好、逻辑通不通
 *   - 不核对事实（价格、地址、参数对不对）—— 那要等知识库改成分块存储
 *   - 不判字数 / 不判有没有 FAQ / 不判 H2 几个 —— 这些按文章类型不同，硬判就是误报
 *
 * 加词只改这个文件，不用碰 执行器.js。加完把 RULES_VERSION 往上抬一位，
 * 界面上的旧结论会自动作废。
 *
 * ── 定级 ────────────────────────────────────────────────────────
 *   fail   确定是硬伤，拦住入库
 *   proof  **可能是真的，但要有出处** —— 也拦，但话不一样：
 *          不是「你写错了」，是「这句得有依据才能发」
 *   warn   疑似，人看一眼（默认折叠，不刷屏）
 * 拿不准的一律放 warn。**误报比漏报致命** —— 被烦两次以后没人再点它。
 *
 * 为什么要 proof 这一档（2026-09-28）：有的品牌真的是全国第一、真的是目前唯一一家。
 * 市场监管总局《广告绝对化用语执法指南》（2023）第六条(六)说得很清楚 ——
 * **限定了具体时间、地域条件**，宣传销量 / 市场占有率等**事实信息**的，不算违规；
 * 但第七条紧跟一句：**广告主无法证明其真实性的，照样查处**。
 * 脚本查不了「能不能举证」（那要等知识库分块），所以不判对错，只提醒「这句要有出处」。
 * 带了限定口径（2024 年 / 中国大陆 / 据 XX 机构）的自动降一档到 warn。
 */

